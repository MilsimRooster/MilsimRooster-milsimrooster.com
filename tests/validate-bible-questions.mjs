import fs from "node:fs";
import assert from "node:assert/strict";
const html=fs.readFileSync("public/bible/questions/index.html","utf8");
const css=fs.readFileSync("public/bible/questions/questions-20260830.css","utf8");
const js=fs.readFileSync("public/bible/questions/questions-20260830.js","utf8");
const bibleHtml=fs.readFileSync("public/bible/index.html","utf8");
assert.ok(html.includes('name="viewport"'),"question guide must define a mobile viewport");
assert.ok(html.includes('id="questionSearch"'),"question guide must provide search");
assert.ok(html.includes('questions-20260830.js?v=20260901-content-audit-1'),"question guide must load the cache-busted audited-content script");
assert.ok(html.includes('id="categoryFilters"'),"question guide must provide category filters");
assert.ok(bibleHtml.includes('href="/bible/questions/"'),"Digital Bible must link to question guide");
assert.equal((js.match(/^q\("/gm)||[]).length,60,"question guide must contain exactly 60 questions");
assert.ok(js.includes("Most likely match"),"search must identify the closest match");
assert.ok(js.includes("aliases"),"search must support paraphrases and synonyms");
assert.ok(js.includes('Ezekiel:"ezekiel"'),"every cited Bible book must have a working deep-link slug");
assert.ok(js.includes('ranked.filter(row=>row.score>0)'),"unmatched searches must not return arbitrary questions");
assert.ok(js.includes('sourceLabel.textContent="Historical sources"'),"historical claims must expose their sources");
assert.ok(js.includes('link.rel="noopener noreferrer"'),"external historical sources must open safely");
assert.ok(js.includes("Christians differ"),"disputed interpretations must be identified as disputed");
assert.ok(js.includes("/bible/#kjv."),"references must open in the Digital Bible");
assert.ok(js.includes('target.searchParams.set("returnTo","questions")'),"Scripture links must preserve their guide origin");
assert.ok(js.includes('target.searchParams.set("question"'),"Scripture links must preserve the exact guide question");
assert.ok(js.includes('target.searchParams.set("guideQuery"'),"Scripture links must preserve the guide search phrase");
assert.ok(js.includes('guideParams.get("question")'),"the guide must restore the originating question");
assert.ok(css.includes("@media(max-width:680px)"),"question guide must provide a mobile layout");
assert.ok(css.includes("overflow-x:auto"),"mobile category controls must remain usable without page overflow");
console.log("Bible question guide validation passed (60 searchable questions, mobile layout, Bible deep links).");
