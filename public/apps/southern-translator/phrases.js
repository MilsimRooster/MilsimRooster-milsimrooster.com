function severityFor(category, index) {
  const bases = { church: 2, grandma: 3, weather: 2, food: 3, family: 3, "small-town": 2, vehicles: 3, work: 2, outdoors: 2, insults: 4, compliments: 1 };
  return Math.min(5, Math.max(1, bases[category] + (index % 3 === 0 ? 1 : 0) - (index % 7 === 0 ? 1 : 0)));
}

function buildPhrasePool() {
  return Object.entries(phraseSeeds).flatMap(([category, phrases]) =>
    phrases.map((phrase, index) => {
      const templates = actualTemplates[category];
      const notes = categoryNotes[category];
      return {
        id: `${category}-${String(index + 1).padStart(2, "0")}`,
        phrase,
        category,
        literalMeaning: literalDescriptions[category][index % literalDescriptions[category].length],
        actualMeanings: [
          templates[index % templates.length],
          templates[(index + 1) % templates.length],
          templates[(index + 2) % templates.length]
        ],
        severity: severityFor(category, index),
        roosterNotes: notes[index % notes.length],
        examples: [
          `${phrase}.`,
          `Somebody heard "${phrase.toLowerCase()}" and adjusted their plans.`
        ]
      };
    })
  );
}

